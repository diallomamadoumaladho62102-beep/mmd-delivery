/**
 * Merge adminUiCatalog.part{1,2,3}.json → adminUiCatalog.json
 * and emit a compact TypeScript module adminUiCatalog.generated.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "i18n");
const parts = ["adminUiCatalog.part1.json", "adminUiCatalog.part2.json", "adminUiCatalog.part3.json"];
const extracted = JSON.parse(
  fs.readFileSync(path.join(dir, "admin-ui-strings.extracted.json"), "utf8")
);

const merged = {};
for (const part of parts) {
  const p = path.join(dir, part);
  if (!fs.existsSync(p)) throw new Error(`Missing ${part}`);
  Object.assign(merged, JSON.parse(fs.readFileSync(p, "utf8")));
}

const missing = [];
for (const row of extracted.strings) {
  if (!merged[row.text]) missing.push(row.text);
}

const locales = ["fr", "es", "ar", "zh", "ff"];
let incomplete = 0;
for (const [k, v] of Object.entries(merged)) {
  for (const loc of locales) {
    if (!v?.[loc] || typeof v[loc] !== "string" || !v[loc].trim()) {
      incomplete += 1;
      console.warn("incomplete", loc, JSON.stringify(k).slice(0, 80));
    }
  }
}

const outJson = path.join(dir, "adminUiCatalog.json");
fs.writeFileSync(outJson, JSON.stringify(merged, null, 2));

const ts = `/* AUTO-GENERATED by scripts/merge-admin-ui-catalog.mjs — do not edit by hand */
import type { WebLocale } from "@/i18n/locales";

export type AdminUiTranslation = Record<Exclude<WebLocale, "en">, string>;

export const ADMIN_UI_CATALOG: Record<string, AdminUiTranslation> = ${JSON.stringify(merged, null, 2)} as const;
`;
fs.writeFileSync(path.join(dir, "adminUiCatalog.generated.ts"), ts);

console.log(
  JSON.stringify(
    {
      mergedKeys: Object.keys(merged).length,
      expected: extracted.total,
      missing: missing.length,
      incomplete,
      missingSample: missing.slice(0, 10),
    },
    null,
    2
  )
);
