function looksFrench(s) {
  if (FR_TO_EN[s]) return true;
  if (/[àâäéèêëïîôùûüçœæÀÂÄÉÈÊËÏÎÔÙÛÜÇ]/.test(s)) return true;
  if (
    /\b(le|la|les|des|une|pour|avec|sans|dans|sur|être|êtes|vous|nous|cette|ce|ces|statut|chargement|enregistrer|actualiser|supprimer|chauffeur|commande|paiement)\b/i.test(
      s
    )
  ) {
    return true;
  }
  return false;
}

function guessEn(source) {
  if (FR_TO_EN[source]) return FR_TO_EN[source];
  // light phrase replacements
  let out = source;
  const pairs = Object.entries(FR_TO_EN).sort((a, b) => b[0].length - a[0].length);
  for (const [fr, en] of pairs) {
    if (fr.length < 4) continue;
    out = out.split(fr).join(en);
  }
  return out;
}

let addedEn = 0;
let frenchKeys = 0;
for (const [key, entry] of Object.entries(catalog)) {
  if (looksFrench(key)) {
    frenchKeys += 1;
    if (!entry.en) {
      entry.en = guessEn(key);
      addedEn += 1;
    }
  }
  // Ensure fr exists for English keys (already should)
  // For French keys, ensure fr is the source if missing
  if (looksFrench(key) && !entry.fr) entry.fr = key;
}

fs.writeFileSync(catalogPath, JSON.stringify(catalog, null, 2));

