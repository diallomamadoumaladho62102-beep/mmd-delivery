function mergeDeep(base, extra) {
  if (Array.isArray(extra) || extra === null || typeof extra !== "object") return extra;
  const out = { ...(base && typeof base === "object" ? base : {}) };
  for (const [k, v] of Object.entries(extra)) {
    out[k] = mergeDeep(out[k], v);
  }
  return out;
}

